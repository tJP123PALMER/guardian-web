/*
 Guardian MDT - Browser Development Preview
 Browser-only helper. Does not affect FiveM NUI behaviour.
*/
window.GetParentResourceName = window.GetParentResourceName || function () {
  return "guardian_mdt_preview";
};

(function () {
  const nativeFetch = window.fetch.bind(window);
  window.fetch = function (url, options) {
    console.log("[Preview NUI]", url, options && options.body ? options.body : "");
    return Promise.resolve({
      ok: true,
      status: 200,
      json: () => Promise.resolve({ ok: true, preview: true }),
      text: () => Promise.resolve(JSON.stringify({ ok: true, preview: true }))
    });
  };

  function post(data) {
    window.postMessage(data, "*");
  }

  function seed() {
    post({ type: "open" });
    post({ type: "setCallsign", callsign: "E21" });
    post({
      type: "loadIncidents",
      incidents: [
        { id: 2401, type: "Structure Fire", postal: "AB12", address: "High Street, Station Area",
          description: "Smoke reported from a two-storey building. Crews requested to investigate." },
        { id: 2402, type: "RTC", postal: "AB13", address: "Main Road / Junction",
          description: "Two vehicle road traffic collision. One lane obstructed." }
      ]
    });
    const now = new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });
    post({ type: "message", item: { sender: "Control", time: now, text: "Welcome to the Guardian MDT browser preview." } });
    post({ type: "message", item: { sender: "Control", time: now, text: "Use the header buttons and bottom This Incident control to test the interface." } });
  }

  function addIncident() {
    post({ type: "incident", item: {
      id: Math.floor(1000 + Math.random() * 8999), type: "Test Incident",
      postal: "AB99", address: "Browser Preview Road",
      description: "This incident was generated by the browser preview toolbar."
    }});
  }
  function addMessage() {
    post({ type: "message", item: {
      sender: "Control",
      time: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
      text: "Test message sent from the browser preview."
    }});
  }
  function mobilising() { post({ type: "mobilising" }); }
  function reset() { location.reload(); }

  function init() {
    if (document.getElementById("previewToolbar")) return;
    const toolbar = document.createElement("div");
    toolbar.id = "previewToolbar";
    toolbar.innerHTML = `
      <strong>GUARDIAN MDT — BROWSER PREVIEW</strong>
      <button id="previewIncident">+ Incident</button>
      <button id="previewMessage">+ Message</button>
      <button id="previewMobilising">Mobilising</button>
      <button id="previewReset">Reset</button>
    `;
    const style = document.createElement("style");
    style.textContent = `
      #previewToolbar{position:fixed;z-index:99999;top:12px;left:50%;transform:translateX(-50%);
        display:flex;align-items:center;gap:8px;padding:9px 12px;border-radius:8px;
        background:rgba(20,29,38,.96);color:#fff;font:13px Arial,sans-serif;
        box-shadow:0 4px 18px rgba(0,0,0,.3)}
      #previewToolbar strong{margin-right:5px}
      #previewToolbar button{border:0;border-radius:5px;padding:6px 9px;cursor:pointer;background:#557a9f;color:#fff}
      #previewToolbar button:hover{filter:brightness(1.15)}
      body{background:#222!important}
    `;
    document.head.appendChild(style);
    document.body.appendChild(toolbar);
    document.getElementById("previewIncident").onclick = addIncident;
    document.getElementById("previewMessage").onclick = addMessage;
    document.getElementById("previewMobilising").onclick = mobilising;
    document.getElementById("previewReset").onclick = reset;

    // ui.js has now registered its message listener. Initialise after it has loaded.
    setTimeout(seed, 50);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init, { once: true });
  } else {
    init();
  }
})();
